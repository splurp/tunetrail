/// Colours for the stylised 3D map.
class MapPalette {
  const MapPalette({
    required this.ground,
    required this.field,
    required this.forest,
    required this.park,
    required this.sand,
    required this.campus,
    required this.parking,
    required this.plaza,
    required this.water,
    required this.roadMinor,
    required this.roadMajor,
    required this.roadHighway,
    required this.buildingWall,
    required this.buildingRoof,
    required this.buildingEdge,
    required this.skyTop,
    required this.skyBottom,
    required this.accent,
    this.checker,
  });

  final Color ground, field, forest, park, sand, campus, parking, plaza, water;
  final Color roadMinor, roadMajor, roadHighway;
  final Color buildingWall, buildingRoof, buildingEdge;
  final Color skyTop, skyBottom, accent;

  /// When set, the ground is a world-anchored checkerboard of [ground] and
  /// this colour (used by Vaporwave).
  final Color? checker;

  Color layer(GroundLayer l) => switch (l) {
        GroundLayer.field => field,
        GroundLayer.forest => forest,
        GroundLayer.park => park,
        GroundLayer.sand => sand,
        GroundLayer.campus => campus,
        GroundLayer.parking => parking,
        GroundLayer.plaza => plaza,
        GroundLayer.water => water,
        GroundLayer.roadMinor => roadMinor,
        GroundLayer.roadMajor => roadMajor,
        GroundLayer.roadHighway => roadHighway,
      };
}

